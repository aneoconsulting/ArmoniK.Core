using System.Collections.Generic;
using System.Globalization;
using System.Linq;

namespace ArmoniK.Samples.Graph.Common.Tests;

/// <summary>
///   Logical positions of the tasks as strings, see <see cref="GraphTask.PositionHash" />. The generator only keeps
///   their hashes; the tests rebuild the strings to check the hashes and to describe graphs readably.
/// </summary>
internal static class Positions
{
  /// <summary>
  ///   Position of the task <paramref name="index" /> of the level <paramref name="level" /> of the graph generated by
  ///   the task at <paramref name="parent" />
  /// </summary>
  /// <param name="parent">Position of the task generating the graph, empty for the client</param>
  /// <param name="level">Level of the task</param>
  /// <param name="index">Index of the task in its level</param>
  /// <returns>
  ///   The position of the task
  /// </returns>
  public static string Child(string parent,
                             int    level,
                             int    index)
  {
    var local = string.Create(CultureInfo.InvariantCulture,
                              $"{level}.{index}");
    return parent.Length == 0
             ? local
             : $"{parent}/{local}";
  }

  /// <summary>
  ///   Position of <paramref name="task" />, in the graph generated by the task at <paramref name="graphPosition" />
  /// </summary>
  public static string Of(GraphTask task,
                          string    graphPosition)
    => Child(graphPosition,
             task.Level,
             task.Index);

  /// <summary>
  ///   Every graph of the session with the position of the task that generates it (empty for the client graph): the
  ///   client graph first, then the sub-graphs in depth first order
  /// </summary>
  public static IEnumerable<(string Position, TaskGraph Graph)> AllGraphs(GraphSettings settings,
                                                                          int           nTasks)
  {
    var stack = new Stack<(string Position, TaskGraph Graph)>();
    stack.Push((string.Empty, GraphGenerator.GenerateRoot(settings,
                                                          nTasks)));
    while (stack.Count > 0)
    {
      var (position, graph) = stack.Pop();
      yield return (position, graph);
      foreach (var task in graph.Tasks.Where(t => t.IsExpanding)
                                .Reverse())
      {
        stack.Push((Of(task,
                       position), GraphGenerator.GenerateSubGraph(settings,
                                                                  task)));
      }
    }
  }
}
