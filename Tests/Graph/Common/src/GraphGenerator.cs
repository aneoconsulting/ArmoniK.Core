using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;

namespace ArmoniK.Samples.Graph.Common;

/// <summary>
///   Generates the graphs from the settings.
/// </summary>
/// <remarks>
///   <para>
///     Budget rule: every task has a budget, the number of tasks it stands for, itself included. A task with budget 1 is
///     a plain task. A task with budget B &gt; 1 counts for 1 and spreads the B-1 remaining over a sub-graph it submits
///     itself, and delegates its output to the last task of this sub-graph. The client is the root with budget NTasks
///     but is not a task: it spreads the whole NTasks over the client graph. Hence the session has exactly NTasks tasks.
///   </para>
///   <para>
///     Reproducibility: a graph is generated by a <see cref="DeterministicRandom" /> seeded only from the seed, the
///     position of the task that generates it and its budget, so the same settings give the same full graph everywhere.
///   </para>
/// </remarks>
public static class GraphGenerator
{
  private const int MaxDraws = 32;

  /// <summary>
  ///   Generates the client graph, whose tasks share <paramref name="nTasks" />
  /// </summary>
  /// <param name="settings">Graph settings</param>
  /// <param name="nTasks">Total number of tasks of the session</param>
  /// <returns>
  ///   The client graph
  /// </returns>
  public static TaskGraph GenerateRoot(GraphSettings settings,
                                       int           nTasks)
  {
    ArgumentOutOfRangeException.ThrowIfNegativeOrZero(nTasks);
    return Generate(settings,
                    string.Empty,
                    StableHash.Fnv1A64(string.Empty),
                    nTasks,
                    false,
                    0);
  }

  /// <summary>
  ///   Generates the sub-graph of an expanding task, whose tasks share <paramref name="budget" /> - 1
  /// </summary>
  /// <param name="settings">Graph settings</param>
  /// <param name="position">Position of the expanding task</param>
  /// <param name="budget">Budget of the expanding task, greater than 1</param>
  /// <param name="outputSize">
  ///   Size of the output of the expanding task, given to the aggregator of the sub-graph that produces it
  /// </param>
  /// <returns>
  ///   The sub-graph, whose last level contains only its aggregator
  /// </returns>
  public static TaskGraph GenerateSubGraph(GraphSettings settings,
                                           string        position,
                                           int           budget,
                                           long          outputSize)
  {
    ArgumentException.ThrowIfNullOrEmpty(position);
    if (budget < 2)
    {
      throw new ArgumentOutOfRangeException(nameof(budget),
                                            budget,
                                            "Only tasks with a budget greater than 1 have a sub-graph");
    }

    return Generate(settings,
                    position,
                    StableHash.Fnv1A64(position),
                    budget - 1,
                    true,
                    outputSize);
  }

  /// <summary>
  ///   Generates the sub-graph of an expanding task without building the position strings of its tasks (they are
  ///   empty); only <see cref="GraphTask.PositionHash" /> is set. Used to compute the statistics with a memory that does
  ///   not grow with the nesting depth.
  /// </summary>
  /// <param name="settings">Graph settings</param>
  /// <param name="task">Expanding task</param>
  /// <returns>
  ///   The sub-graph of the task, identical to <see cref="GenerateSubGraph(GraphSettings, GraphTask)" /> but positions
  /// </returns>
  internal static TaskGraph GenerateSubGraphWithoutPositions(GraphSettings settings,
                                                             GraphTask     task)
    => GenerateSubGraph(settings,
                        task.PositionHash,
                        task.Budget,
                        task.OutputSize);

  /// <summary>
  ///   Generates the sub-graph of an expanding task from the hash of its position, without building the position
  ///   strings of its tasks (they are empty); only <see cref="GraphTask.PositionHash" /> is set. Used by the workers,
  ///   whose payloads carry only the hash, so that their size does not grow with the nesting depth.
  /// </summary>
  /// <param name="settings">Graph settings</param>
  /// <param name="positionHash">
  ///   Hash of the position of the expanding task, see <see cref="GraphTask.PositionHash" />
  /// </param>
  /// <param name="budget">Budget of the expanding task, greater than 1</param>
  /// <param name="outputSize">
  ///   Size of the output of the expanding task, given to the aggregator of the sub-graph that produces it
  /// </param>
  /// <returns>
  ///   The sub-graph, identical to <see cref="GenerateSubGraph(GraphSettings, string, int, long)" /> but positions
  /// </returns>
  public static TaskGraph GenerateSubGraph(GraphSettings settings,
                                           ulong         positionHash,
                                           int           budget,
                                           long          outputSize)
  {
    if (budget < 2)
    {
      throw new ArgumentOutOfRangeException(nameof(budget),
                                            budget,
                                            "Only tasks with a budget greater than 1 have a sub-graph");
    }

    return Generate(settings,
                    null,
                    positionHash,
                    budget - 1,
                    true,
                    outputSize);
  }

  /// <summary>
  ///   Generates the sub-graph of an expanding task of a graph
  /// </summary>
  /// <param name="settings">Graph settings</param>
  /// <param name="task">Expanding task</param>
  /// <returns>
  ///   The sub-graph of the task
  /// </returns>
  public static TaskGraph GenerateSubGraph(GraphSettings settings,
                                           GraphTask     task)
    => GenerateSubGraph(settings,
                        task.Position,
                        task.Budget,
                        task.OutputSize);

  /// <summary>
  ///   Seed of the graph generated by the task at <paramref name="position" /> with <paramref name="budget" />
  /// </summary>
  /// <param name="seed">Seed of the settings</param>
  /// <param name="position">Position of the task generating the graph, empty for the client</param>
  /// <param name="budget">Budget of the task generating the graph, NTasks for the client</param>
  /// <returns>
  ///   The seed of the graph
  /// </returns>
  public static ulong GraphSeed(ulong  seed,
                                string position,
                                int    budget)
    => GraphSeed(seed,
                 StableHash.Fnv1A64(position),
                 budget);

  private static ulong GraphSeed(ulong seed,
                                 ulong positionHash,
                                 int   budget)
    => StableHash.Combine(seed,
                          positionHash,
                          (ulong)budget);

  /// <summary>
  ///   Hash of <see cref="ChildPosition" />, computed from the hash of the parent position
  /// </summary>
  private static ulong ChildPositionHash(ulong parentHash,
                                         bool  isRoot,
                                         int   level,
                                         int   index)
  {
    var hash = isRoot
                 ? parentHash
                 : StableHash.Fnv1A64(parentHash,
                                      "/");
    return StableHash.Fnv1A64(hash,
                              string.Create(CultureInfo.InvariantCulture,
                                            $"{level}.{index}"));
  }

  /// <summary>
  ///   Position of the task <paramref name="index" /> of the level <paramref name="level" /> of the graph generated by
  ///   the task at <paramref name="parent" />
  /// </summary>
  /// <param name="parent">Position of the task generating the graph, empty for the client</param>
  /// <param name="level">Level of the task</param>
  /// <param name="index">Index of the task in its level</param>
  /// <returns>
  ///   The position of the task
  /// </returns>
  public static string ChildPosition(string parent,
                                     int    level,
                                     int    index)
  {
    var local = string.Create(CultureInfo.InvariantCulture,
                              $"{level}.{index}");
    return parent.Length == 0
             ? local
             : $"{parent}/{local}";
  }

  /// <param name="position">Position of the generating task, null to skip building the positions of the tasks</param>
  /// <param name="positionHash">Hash of the position of the generating task</param>
  private static TaskGraph Generate(GraphSettings settings,
                                    string?       position,
                                    ulong         positionHash,
                                    int           shared,
                                    bool          isSubGraph,
                                    long          aggregatorOutputSize)
  {
    var random = new DeterministicRandom(GraphSeed(settings.Seed,
                                                   positionHash,
                                                   isSubGraph
                                                     ? shared + 1
                                                     : shared));

    var n = Math.Min(shared,
                     settings.GraphTasks.SampleCount(random,
                                                     1));

    int[] levelSizes;
    if (!isSubGraph)
    {
      levelSizes = settings.TasksPerLevel.Split(n,
                                                Math.Min(settings.Levels,
                                                         n));
    }
    else if (n == 1)
    {
      levelSizes = new[]
                   {
                     1,
                   };
    }
    else
    {
      // The last level only holds the aggregator; it needs a level of its own even when Levels is 1
      var levels = Math.Max(2,
                            Math.Min(settings.Levels,
                                     n));
      levelSizes = settings.TasksPerLevel.Split(n      - 1,
                                                levels - 1)
                           .Append(1)
                           .ToArray();
    }

    var budgets = SplitBudget(random,
                              shared,
                              n);

    var levelStarts = new int[levelSizes.Length];
    for (var l = 1; l < levelSizes.Length; l++)
    {
      levelStarts[l] = levelStarts[l - 1] + levelSizes[l - 1];
    }

    var chooser = new DependencyChooser(settings,
                                        random,
                                        levelSizes,
                                        levelStarts);
    var tasks = new List<GraphTask>(n);

    for (var l = 0; l < levelSizes.Length; l++)
    {
      for (var i = 0; i < levelSizes[l]; i++)
      {
        var id = tasks.Count;
        var duration = (int)Math.Min(int.MaxValue,
                                     Math.Round(settings.TaskDuration.SampleNonNegative(random),
                                                MidpointRounding.AwayFromZero));
        var outputSize = (long)Math.Min(long.MaxValue / 2,
                                        Math.Round(settings.OutputSize.SampleNonNegative(random) * 1024,
                                                   MidpointRounding.AwayFromZero));
        var isAggregator = isSubGraph && id == n - 1;
        if (isAggregator)
        {
          outputSize = aggregatorOutputSize;
        }

        IReadOnlyList<int> dependencies = Array.Empty<int>();
        if (l > 0)
        {
          var k = settings.DependenciesPerTask.SampleCount(random,
                                                           0);
          if (isAggregator)
          {
            k = Math.Max(k,
                         1);
          }

          dependencies = chooser.Choose(l,
                                        i,
                                        k);
        }

        tasks.Add(new GraphTask(id,
                                l,
                                i,
                                position is null
                                  ? string.Empty
                                  : ChildPosition(position,
                                                  l,
                                                  i),
                                budgets[id],
                                duration,
                                outputSize,
                                dependencies)
                  {
                    PositionHash = ChildPositionHash(positionHash,
                                                     !isSubGraph,
                                                     l,
                                                     i),
                  });
      }
    }

    return new TaskGraph(position ?? string.Empty,
                         shared,
                         isSubGraph,
                         levelSizes,
                         tasks);
  }

  /// <summary>
  ///   Splits <paramref name="total" /> among <paramref name="n" /> tasks at random, each getting at least 1
  /// </summary>
  private static int[] SplitBudget(DeterministicRandom random,
                                   int                 total,
                                   int                 n)
  {
    var budgets = Enumerable.Repeat(1,
                                    n)
                            .ToArray();
    var remaining = total - n;
    if (remaining > 0)
    {
      // Exponential weights give a uniform split of the remaining budget (flat Dirichlet)
      var weights = new double[n];
      for (var i = 0; i < n; i++)
      {
        weights[i] = -Math.Log(random.NextDoubleNonZero());
      }

      LevelShape.Distribute(budgets,
                            weights,
                            remaining);
    }

    return budgets;
  }

  /// <summary>
  ///   Chooses the data dependencies of the tasks of one graph
  /// </summary>
  private sealed class DependencyChooser
  {
    private readonly int[]                     levelSizes_;
    private readonly int[]                     levelStarts_;
    private readonly DeterministicRandom       random_;
    private readonly GraphSettings             settings_;
    private readonly Dictionary<int, double[]> zipfCdfs_ = new();

    public DependencyChooser(GraphSettings       settings,
                             DeterministicRandom random,
                             int[]               levelSizes,
                             int[]               levelStarts)
    {
      settings_    = settings;
      random_      = random;
      levelSizes_  = levelSizes;
      levelStarts_ = levelStarts;
    }

    /// <summary>
    ///   Chooses <paramref name="k" /> distinct outputs among the earlier levels for the task <paramref name="index" />
    ///   of the level <paramref name="level" />
    /// </summary>
    public List<int> Choose(int level,
                            int index,
                            int k)
    {
      var skip = settings_.SkipLevels > 0;
      // Without SkipLevels, only the previous level is a candidate
      var candidates = skip
                         ? levelStarts_[level]
                         : levelSizes_[level - 1];
      k = Math.Min(k,
                   candidates);

      var chosen     = new List<int>(k);
      var picked     = new HashSet<int>();
      var usedCounts = new Dictionary<int, int>();
      var relative   = (index + 0.5) / levelSizes_[level];

      for (var d = 0; d < k; d++)
      {
        var from = level - 1;
        if (skip && level >= 2 && random_.NextDouble() < settings_.SkipLevels)
        {
          from = random_.NextInt(level - 1);
        }

        // When the chosen level is exhausted, fall back on the closest older level that still has free outputs
        if (usedCounts.GetValueOrDefault(from) >= levelSizes_[from])
        {
          from = level - 1;
          while (usedCounts.GetValueOrDefault(from) >= levelSizes_[from])
          {
            from--;
          }
        }

        var id = levelStarts_[from] + PickInLevel(from,
                                                  relative,
                                                  picked);
        picked.Add(id);
        chosen.Add(id);
        usedCounts[from] = usedCounts.GetValueOrDefault(from) + 1;
      }

      return chosen;
    }

    private int PickInLevel(int          level,
                            double       relative,
                            HashSet<int> picked)
    {
      var size  = levelSizes_[level];
      var start = levelStarts_[level];

      bool IsFree(int i)
        => !picked.Contains(start + i);

      switch (settings_.ParentChoice.Kind)
      {
        case ParentChoiceKind.Local:
        {
          var target = Math.Min(size - 1,
                                (int)Math.Floor(relative * size));
          // Closest free neighbour: target, target + 1, target - 1, target + 2...
          for (var offset = 0; offset < 2 * size; offset++)
          {
            var i = target + ((offset & 1) == 0
                                ? offset / 2
                                : -(offset / 2 + 1));
            if (i >= 0 && i < size && IsFree(i))
            {
              return i;
            }
          }

          break;
        }
        case ParentChoiceKind.Zipf:
        {
          var cdf = ZipfCdf(size);
          for (var draw = 0; draw < MaxDraws; draw++)
          {
            var u = random_.NextDouble() * cdf[^1];
            var i = Array.BinarySearch(cdf,
                                       u);
            i = i < 0
                  ? ~i
                  : i + 1;
            i = Math.Min(i,
                         size - 1);
            if (IsFree(i))
            {
              return i;
            }
          }

          // Most popular free output
          for (var i = 0; i < size; i++)
          {
            if (IsFree(i))
            {
              return i;
            }
          }

          break;
        }
        default:
        {
          var i = 0;
          for (var draw = 0; draw < MaxDraws; draw++)
          {
            i = random_.NextInt(size);
            if (IsFree(i))
            {
              return i;
            }
          }

          // Next free output after the last draw
          for (var offset = 1; offset <= size; offset++)
          {
            var j = (i + offset) % size;
            if (IsFree(j))
            {
              return j;
            }
          }

          break;
        }
      }

      throw new InvalidOperationException($"No free output in level {level}");
    }

    private double[] ZipfCdf(int size)
    {
      if (zipfCdfs_.TryGetValue(size,
                                out var cdf))
      {
        return cdf;
      }

      cdf = new double[size];
      var sum = 0.0;
      for (var r = 0; r < size; r++)
      {
        sum += 1.0 / Math.Pow(r + 1,
                              settings_.ParentChoice.Exponent);
        cdf[r] = sum;
      }

      zipfCdfs_[size] = cdf;
      return cdf;
    }
  }
}
