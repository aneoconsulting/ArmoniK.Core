using System.Collections.Generic;

namespace ArmoniK.Samples.Graph.Common;

/// <summary>
///   A task of a generated graph
/// </summary>
/// <param name="Id">Index of the task in its graph; the tasks are sorted by level, so dependencies have lower ids</param>
/// <param name="Level">Level of the task in its graph</param>
/// <param name="Index">Index of the task in its level</param>
/// <param name="Budget">Number of tasks the task stands for, itself included; above 1 the task expands into a sub-graph</param>
/// <param name="DurationMs">Time the task sleeps, in milliseconds</param>
/// <param name="OutputSize">Size in bytes of the output of the task</param>
/// <param name="Dependencies">Ids of the tasks of the same graph whose outputs are data dependencies of this task</param>
public sealed record GraphTask(int                Id,
                               int                Level,
                               int                Index,
                               int                Budget,
                               int                DurationMs,
                               long               OutputSize,
                               IReadOnlyList<int> Dependencies)
{
  /// <summary>
  ///   FNV-1a hash of the logical position of the task, computed incrementally from the hash of the position of the
  ///   task that generates its graph. The position is <c>level.index</c> for each nesting, joined by <c>/</c>, e.g.
  ///   <c>2.17/0.3</c> is the task 3 of the level 0 of the sub-graph generated by the task 17 of the level 2 of the
  ///   client graph. Only the hash is kept: the position grows with the nesting depth.
  /// </summary>
  public ulong PositionHash { get; init; }

  /// <summary>
  ///   Whether the task submits a sub-graph and delegates its output to the last task of this sub-graph
  /// </summary>
  public bool IsExpanding
    => Budget > 1;
}

/// <summary>
///   A generated graph: either the client graph or the sub-graph of an expanding task
/// </summary>
/// <param name="PositionHash">
///   Hash of the position of the task that generates this graph, the hash of the empty string for the client graph
/// </param>
/// <param name="Budget">Number of tasks shared by the tasks of this graph (sub-graphs included)</param>
/// <param name="IsSubGraph">Whether this graph is the sub-graph of an expanding task</param>
/// <param name="LevelSizes">Number of tasks of each level</param>
/// <param name="Tasks">Tasks of the graph, sorted by level then index</param>
public sealed record TaskGraph(ulong                    PositionHash,
                               int                      Budget,
                               bool                     IsSubGraph,
                               IReadOnlyList<int>       LevelSizes,
                               IReadOnlyList<GraphTask> Tasks)
{
  /// <summary>
  ///   Last task of the graph; for a sub-graph, it produces the output of the task that generated it
  /// </summary>
  public GraphTask Aggregator
    => Tasks[^1];
}
